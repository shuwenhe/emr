from __future__ import annotations

from typing import Any, Dict, Optional, Protocol


class PlatformGateway(Protocol):
    def init_db(self) -> None: ...

    async def poll_device_drop(self, stop_event: Any) -> None: ...

    def import_history(self, root_path: str, analyze: bool = True) -> Dict[str, Any]: ...

    def summary(self) -> Dict[str, Any]: ...

    def list_records(self, patient_id: Optional[str] = None, limit: int = 50) -> Any: ...

    def list_platform_emrs(
        self,
        patient_id: Optional[str] = None,
        record_id: Optional[str] = None,
        limit: int = 50,
        include_archived: bool = False,
    ) -> Any: ...

    def upsert_patient(self, payload: Dict[str, Any]) -> Optional[str]: ...

    def list_patients(self, limit: int = 20, offset: int = 0, include_archived: bool = False) -> Any: ...

    def get_patient(self, patient_id: str) -> Any: ...

    def update_patient(self, patient_id: str, payload: Dict[str, Any]) -> Any: ...

    def archive_patient(self, patient_id: str, archived: bool = True) -> Any: ...

    def delete_patient(self, patient_id: str) -> bool: ...
